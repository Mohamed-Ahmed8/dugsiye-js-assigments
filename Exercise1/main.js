let x = 7;
let y = 3;

console.log(x + y);

console.log(x - y);

console.log(x * y);

console.log(x / y);

console.log(x % y);

console.log("Pre Increment");
console.log(++x);

console.log("Post Increment");
console.log(x++);
console.log(x);

console.log("Pre Decrement")
console.log(--y);

console.log("Post Decrement");
console.log(y--);
console.log(y)